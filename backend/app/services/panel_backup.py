"""The panel's own backup, for rebuilding a lost server (disaster recovery).

Per-account backups bring back websites, databases and mailboxes. They do
not bring back the panel: its database (accounts, packages, destinations,
schedules, settings), .env and the SECRET_KEY that decrypts every stored
secret, /etc/spanel (the audit key, the panel certificate), Let's Encrypt
certificates, DKIM keys, the PowerDNS zones, the nginx/PHP/mail
configuration the panel wrote. Without those a new server cannot even
decrypt the credentials of the destination the account backups are on.

The helper builds and encrypts the archive as root (panel-dr-archive), with
a passphrase only root can read; this module schedules it, sends it to the
chosen destinations under <hostname>/_panel-dr/, prunes old copies there and
keeps the record. `spanel dr-restore <file>` on a fresh install puts it back
(docs/ADMIN_AND_CLI_GUIDE.md, "Disaster recovery").

Passphrase escrow: the passphrase is generated by the helper and shown
exactly once. Scheduled runs refuse to start until an administrator has
typed it back (confirm_passphrase) - proof that a copy exists somewhere
other than this server, which is the only place an archive is useless
without it.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
from datetime import datetime
from pathlib import Path
from typing import Optional

from app.core.config import settings
from app.services.shell import shell

DATA_DIR = Path(os.environ.get("SPANEL_DATA_DIR") or os.environ.get("spanel_DATA_DIR") or "/var/lib/spanel")
CONFIG_FILE = DATA_DIR / "panel-dr.json"
REMOTE_FOLDER = "_panel-dr"
ARCHIVE_SUFFIX = ".spdr"
ARCHIVE_RE = re.compile(r"^panel-dr-[A-Za-z0-9.-]{1,63}-\d{8}T\d{6}Z\.spdr$")
WINDOW_RE = re.compile(r"^(?:[01]\d|2[0-3]):[0-5]\d$")

DEFAULTS = {
    "enabled": False,
    "window": "01:30",
    "weekdays": [],
    "target_ids": [],
    "keep_remote": 14,
    "escrow": {"fingerprint": "", "shown_at": "", "confirmed_at": ""},
    "last_run": {},
    "history": [],
}


def local_dir() -> Path:
    return Path(settings.backup_root) / "panel-dr"


def load_config() -> dict:
    try:
        stored = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        stored = {}
    config = json.loads(json.dumps(DEFAULTS))
    if isinstance(stored, dict):
        for key, value in stored.items():
            if key in config:
                config[key] = value
    return config


def _write(config: dict) -> None:
    CONFIG_FILE.parent.mkdir(parents=True, exist_ok=True)
    tmp = CONFIG_FILE.with_suffix(".tmp")
    tmp.write_text(json.dumps(config, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    try:
        os.chmod(tmp, 0o640)
    except OSError:
        pass
    tmp.replace(CONFIG_FILE)


def fingerprint(passphrase: str) -> str:
    """What the helper prints for the passphrase file: sha256, first 16 hex."""
    return hashlib.sha256((passphrase or "").strip().encode("utf-8")).hexdigest()[:16]


def parse_helper_output(stdout: str) -> dict:
    found = {}
    for line in (stdout or "").splitlines():
        key, sep, value = line.strip().partition("=")
        if sep and re.fullmatch(r"[a-z_]+", key):
            found[key] = value
    return found


# --- passphrase escrow -----------------------------------------------------------

def key_status() -> dict:
    res = shell.privileged("panel-dr-key-status", check=False, fallback=["bash", "-lc", "echo initialised=no"])
    found = parse_helper_output(res.stdout)
    escrow = load_config()["escrow"]
    initialised = found.get("initialised") == "yes"
    current = found.get("fingerprint", "")
    return {
        "initialised": initialised,
        "fingerprint": current,
        "confirmed": bool(initialised and escrow.get("confirmed_at") and escrow.get("fingerprint") == current),
        "shown_at": escrow.get("shown_at", ""),
        "confirmed_at": escrow.get("confirmed_at", "") if escrow.get("fingerprint") == current else "",
    }


def init_passphrase(rotate: bool = False) -> dict:
    """Create (or rotate) the passphrase and return it - the one time it is
    ever returned. Rotating means older archives need the OLD passphrase."""
    try:
        # No fallback on purpose: a passphrase is only ever made by the helper,
        # as root, into a file the panel account cannot read.
        res = shell.privileged("panel-dr-key-init", helper_args=(["--rotate"] if rotate else []), check=False)
    except RuntimeError as exc:
        raise ValueError("The privileged helper is not available on this machine") from exc
    if res.returncode != 0:
        raise ValueError((res.stderr or res.stdout or "Could not create the passphrase").strip()[-300:])
    found = parse_helper_output(res.stdout)
    passphrase = found.get("passphrase", "")
    if not passphrase:
        raise ValueError("The helper did not return a passphrase")
    config = load_config()
    config["escrow"] = {"fingerprint": found.get("fingerprint") or fingerprint(passphrase),
                        "shown_at": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"), "confirmed_at": ""}
    _write(config)
    return {"passphrase": passphrase, "fingerprint": config["escrow"]["fingerprint"],
            "warning": "Store this passphrase outside this server now. It is not shown again, and without it "
                       "the panel self-backup cannot be restored."}


def confirm_passphrase(typed: str) -> dict:
    """The administrator types the passphrase back; it must match the file."""
    status = key_status()
    if not status["initialised"]:
        raise ValueError("No passphrase has been created yet")
    if fingerprint(typed) != status["fingerprint"]:
        raise ValueError("That is not the passphrase. Check the copy you stored.")
    config = load_config()
    config["escrow"].update({"fingerprint": status["fingerprint"],
                             "confirmed_at": datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")})
    _write(config)
    return key_status()


# --- settings ------------------------------------------------------------------------

def save_settings(changes: dict, valid_target_ids: Optional[set[int]] = None) -> dict:
    config = load_config()
    if changes.get("enabled") is not None:
        config["enabled"] = bool(changes["enabled"])
    if changes.get("window") is not None:
        if not WINDOW_RE.match(str(changes["window"])):
            raise ValueError("The window must be HH:MM (24-hour)")
        config["window"] = str(changes["window"])
    if changes.get("weekdays") is not None:
        config["weekdays"] = sorted({int(d) for d in changes["weekdays"] if 0 <= int(d) <= 6})
    if changes.get("target_ids") is not None:
        ids = [int(i) for i in changes["target_ids"]]
        if valid_target_ids is not None:
            unknown = [i for i in ids if i not in valid_target_ids]
            if unknown:
                raise ValueError(f"Unknown backup destination: {unknown}")
        config["target_ids"] = sorted(set(ids))
    if changes.get("keep_remote") is not None:
        config["keep_remote"] = max(1, min(365, int(changes["keep_remote"])))
    if config["enabled"] and not config["target_ids"]:
        raise ValueError("Choose at least one destination: an archive kept only on this server is no use when the server is lost")
    _write(config)
    return public_status(config)


def list_local() -> list[dict]:
    folder = local_dir()
    rows = []
    if not folder.is_dir():
        return rows
    for archive in sorted(folder.glob(f"panel-dr-*{ARCHIVE_SUFFIX}"), reverse=True):
        if not ARCHIVE_RE.fullmatch(archive.name):
            continue
        manifest = {}
        try:
            manifest = json.loads(archive.with_suffix(".json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            pass
        rows.append({"name": archive.name, "size": archive.stat().st_size,
                     "created_at": manifest.get("created_at", ""), "sha256": manifest.get("sha256", ""),
                     "db_revision": manifest.get("db_revision", ""), "dns_zones": manifest.get("dns_zones", 0),
                     "paths": len(manifest.get("paths") or [])})
    return rows


def public_status(config: Optional[dict] = None) -> dict:
    config = config or load_config()
    return {
        "enabled": bool(config["enabled"]),
        "window": config["window"],
        "weekdays": config["weekdays"],
        "target_ids": config["target_ids"],
        "keep_remote": config["keep_remote"],
        "last_run": config.get("last_run") or {},
        "history": (config.get("history") or [])[:10],
        "local": list_local(),
        "remote_folder": REMOTE_FOLDER,
    }


# --- the run --------------------------------------------------------------------------

def plan_remote_prune(entries: list[dict], keep: int) -> list[dict]:
    """Self-backups are independent full archives: keep the newest `keep`."""
    archives = [e for e in entries if ARCHIVE_RE.fullmatch(e.get("name") or "")]
    archives.sort(key=lambda e: (e.get("modified") or "", e["name"]), reverse=True)
    return archives[max(1, int(keep)):]


def _targets(db, ids: list[int]) -> list:
    from app.models.entities import SftpBackupTarget

    if not ids:
        return []
    return db.query(SftpBackupTarget).filter(SftpBackupTarget.id.in_(ids), SftpBackupTarget.is_active == True).all()  # noqa: E712


def run_backup(db, trigger: str = "manual") -> dict:
    """Build the archive (helper), send it to every chosen destination, prune
    old copies there. Raises ValueError for a precondition, and records and
    returns a result otherwise."""
    from app.services import backup, backup_remote

    if not key_status()["confirmed"]:
        raise ValueError("Create the passphrase and confirm you stored it before the panel self-backup can run")
    config = load_config()
    started = datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")
    result = {"started_at": started, "trigger": trigger, "archive": "", "uploads": [], "errors": [], "pruned": 0}

    res = shell.privileged("panel-dr-archive", check=False, timeout=3 * 3600,
                           fallback=["bash", "-lc", "echo archive=; echo manifest="])
    found = parse_helper_output(res.stdout)
    archive = found.get("archive", "")
    if res.returncode != 0 or not archive:
        result["errors"].append((res.stderr or res.stdout or "panel-dr-archive failed").strip()[-500:])
    else:
        result["archive"] = Path(archive).name
        host = backup.get_server_hostname()
        subpath = f"{host}/{REMOTE_FOLDER}"
        for target in _targets(db, config["target_ids"]):
            try:
                result["uploads"].append(backup_remote.upload(target, archive, Path(archive).name, subpath, db=db))
                listing = backup_remote.list_files(target, subpath, suffixes=(ARCHIVE_SUFFIX,))
                for old in plan_remote_prune(listing, config["keep_remote"]):
                    backup_remote.delete(target, old["key"])
                    result["pruned"] += 1
            except Exception as exc:  # noqa: BLE001 - one destination failing must not stop the others
                result["errors"].append(f"{target.name}: {exc}")
        if not config["target_ids"]:
            result["errors"].append("No destination chosen: the archive is only on this server")

    result["finished_at"] = datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")
    result["status"] = "ok" if not result["errors"] else ("partial" if result["uploads"] else "failed")
    config = load_config()
    config["last_run"] = result
    config["history"] = [result, *(config.get("history") or [])][:20]
    _write(config)
    if result["status"] != "ok":
        _report_failure(result)
    return result


def _report_failure(result: dict) -> None:
    try:
        from app.services import alert_webhooks

        alert_webhooks.alert("panel_dr_failed", "Panel self-backup failed",
                             "\n".join(result["errors"][:5]), {"status": result["status"]},
                             dedupe_key=f"panel_dr:{result['started_at'][:10]}")
    except Exception:  # noqa: BLE001
        pass


# --- maintenance window hooks -------------------------------------------------------------

def scheduled_window():
    from app.services.maintenance_window import Schedule

    config = load_config()
    if not config["enabled"] or not config["target_ids"]:
        return None
    return Schedule(window=config["window"], weekdays=list(config["weekdays"]))


def scheduled_run() -> tuple[str, str]:
    from app.core.database import SessionLocal

    db = SessionLocal()
    try:
        result = run_backup(db, trigger="scheduled")
    except ValueError as exc:
        return "failed", str(exc)
    finally:
        db.close()
    message = f"{result['archive']} -> {len(result['uploads'])} destination(s)"
    if result["errors"]:
        message += "; " + "; ".join(result["errors"][:3])
    return ("ok" if result["status"] == "ok" else "failed"), message
